const enText: Record<string, string> = Object.fromEntries(
  Object.entries(idText).map(([english, indonesian]) => [indonesian, english]),
);

function restoreEnglish(value: string) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const clean = value.trim();
  if (!clean) return value;
  return leading + (enText[clean] ?? clean) + trailing;
}

function translate(value: string) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const clean = value.trim();
  if (!clean) return value;
  const exact = idText[clean];
  if (exact) return leading + exact + trailing;
  for (const [pattern, replacement] of patterns) {
    const match = clean.match(pattern);
    if (match) return leading + replacement(match) + trailing;
  }
  return value;
}

const originalText = new WeakMap<Text, string>();
const originalAttributes = new WeakMap<Element, Map<string, string>>();

function applyLanguage(language: Language) {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode() as Text | null;
  while (node) {
    if (node.parentElement?.closest("[data-no-translate],script,style,noscript")) { node = walker.nextNode() as Text | null; continue; }
    const current = node.nodeValue ?? "";
    if (language === "en") {
      originalText.set(node, current);
    } else {
      let original = restoreEnglish(originalText.get(node) ?? current);
      const previousTranslation = translate(original);
      if (current !== original && current !== previousTranslation) {
        original = restoreEnglish(current);
        originalText.set(node, original);
      } else if (!originalText.has(node)) {
        originalText.set(node, original);
      }
      const next = translate(original);
      if (current !== next) node.nodeValue = next;
    }
    node = walker.nextNode() as Text | null;
  }
  document.querySelectorAll("[aria-label],[placeholder],[title]").forEach((element) => {
    if (element.closest("[data-no-translate],script,style,noscript")) return;
    let originals = originalAttributes.get(element);
    if (!originals) { originals = new Map(); originalAttributes.set(element, originals); }
    ["aria-label", "placeholder", "title"].forEach((name) => {
      const current = element.getAttribute(name);
      if (current === null) return;
      if (language === "en") { originals!.set(name, current); return; }
      let original = restoreEnglish(originals!.get(name) ?? current);
      const previousTranslation = translate(original);
      if (current !== original && current !== previousTranslation) {
        original = restoreEnglish(current);
        originals!.set(name, original);
      } else if (!originals!.has(name)) {
        originals!.set(name, original);
      }
      const next = translate(original);
      if (current !== next) element.setAttribute(name, next);
    });
  });
  document.documentElement.lang = language;
  document.documentElement.dataset.lang = language;
}

export function SiteLanguage({ language }: { language: Language }) {
  useEffect(() => {
    let active = true;
    let frame = 0;
    const run = () => {
      if (!active) return;
      cancelAnimationFrame(frame);
      frame = requestAnimationFrame(() => { if (active) applyLanguage(language); });
    };
    run();
    const observer = new MutationObserver(run);
    observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "placeholder", "title"] });
    const rerunAfterInteraction = () => {
      run();
      window.setTimeout(run, 0);
    };
    document.addEventListener("click", rerunAfterInteraction, true);
    document.addEventListener("input", rerunAfterInteraction, true);
    document.addEventListener("change", rerunAfterInteraction, true);
    return () => {
      active = false;
      observer.disconnect();
      cancelAnimationFrame(frame);
      document.removeEventListener("click", rerunAfterInteraction, true);
      document.removeEventListener("input", rerunAfterInteraction, true);
      document.removeEventListener("change", rerunAfterInteraction, true);
    };
  }, [language]);
  return null;
}
