create table public.universities (
  id text primary key,
  name text not null,
  city text,
  country text,
  region text,
  website_domain text,
  institution_type text not null default 'university'
    check (institution_type in ('university', 'business_school')),
  parent_university text,
  directory_source text,
  directory_order integer,
  logo_url text,
  identity_source_url text,
  identity_verified_on date,
  publication_status text not null default 'draft'
    check (publication_status in ('draft', 'published', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.programmes (
  id text primary key,
  university_id text not null references public.universities(id) on delete cascade,
  title text not null,
  study_level text not null default 'bachelor'
    check (study_level in ('bachelor', 'postgraduate', 'restricted', 'unknown')),
  duration text,
  credits text,
  teaching_language text,
  subject_areas jsonb not null default '[]'::jsonb
    check (jsonb_typeof(subject_areas) = 'array'),
  official_source_url text not null,
  source_label text,
  source_checked_on date,
  note text,
  verification_status text not null default 'not_yet_verified'
    check (verification_status in ('verified', 'partially_verified', 'not_yet_verified', 'needs_review', 'outdated', 'conflicting')),
  publication_status text not null default 'draft'
    check (publication_status in ('draft', 'published', 'archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (university_id, title)
);

create table public.programme_facts (
  id bigint generated by default as identity primary key,
  programme_id text not null references public.programmes(id) on delete cascade,
  field_key text not null,
  value jsonb,
  status text not null default 'not_yet_verified'
    check (status in ('verified', 'not_yet_verified', 'not_published', 'varies_by_intake', 'varies_by_applicant', 'official_confirmation_required', 'under_review', 'outdated', 'conflicting')),
  source_url text,
  academic_year text not null default '',
  applicant_context text not null default '',
  verified_on date,
  review_due_on date,
  note text,
  is_public boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (programme_id, field_key, academic_year, applicant_context)
);

create index universities_public_order_idx
  on public.universities (publication_status, directory_order);
create index programmes_university_idx
  on public.programmes (university_id, publication_status);
create index programme_facts_programme_idx
  on public.programme_facts (programme_id, is_public);
create index programme_facts_review_idx
  on public.programme_facts (status, review_due_on);

alter table public.universities enable row level security;
alter table public.programmes enable row level security;
alter table public.programme_facts enable row level security;

revoke all on table public.universities from anon, authenticated;
revoke all on table public.programmes from anon, authenticated;
revoke all on table public.programme_facts from anon, authenticated;
grant select on table public.universities to anon, authenticated;
grant select on table public.programmes to anon, authenticated;
grant select on table public.programme_facts to anon, authenticated;
grant insert, update, delete on table public.universities to authenticated;
grant insert, update, delete on table public.programmes to authenticated;
grant insert, update, delete on table public.programme_facts to authenticated;
grant usage, select on sequence public.programme_facts_id_seq to authenticated;

create policy "Published universities are readable"
on public.universities for select
using (publication_status = 'published');

create policy "Published programmes are readable"
on public.programmes for select
using (publication_status = 'published');

create policy "Public programme facts are readable"
on public.programme_facts for select
using (
  is_public
  and exists (
    select 1 from public.programmes p
    where p.id = programme_id and p.publication_status = 'published'
  )
);

